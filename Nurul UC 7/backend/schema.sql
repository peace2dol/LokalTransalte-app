CREATE TABLE IF NOT EXISTS chat_abbreviations (
  abbr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  short_form VARCHAR(50) NOT NULL UNIQUE,
  full_form VARCHAR(100) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_chat_abbreviations_short_form ON chat_abbreviations(short_form);
CREATE TABLE IF NOT EXISTS slang_terms (
  slang_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  term VARCHAR(80) NOT NULL UNIQUE,
  meaning VARCHAR(180) NOT NULL,
  usage_note TEXT NOT NULL DEFAULT ''
);
